// Release manifest: pins the bytes of every program the build produces.
//
//   node scripts/release-manifest.mjs            write release/manifest.json from smart_contracts/artifacts
//   node scripts/release-manifest.mjs --check    exit 1 if the artifacts differ from release/manifest.json
//
// Every deploy and update script sends the programs it finds under smart_contracts/artifacts. The manifest
// is the reviewed record of what those programs are: run `npm run build`, regenerate it, and commit both
// together, so a diff of the manifest shows which programs changed bytes. Before sending anything to a
// network, run the check on a clean checkout of the release tag.
//
// Values come from each ARC-56 spec's `byteCode` (base64). sha256 is over the decoded program. Extra pages
// is the minimum that holds approval + clear. Programs with template variables are hashed as built,
// before substitution.
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const artifacts = path.join(project, 'smart_contracts', 'artifacts')
export const manifestPath = path.join(project, 'release', 'manifest.json')

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')

function specFiles(dir) {
  const found = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) found.push(...specFiles(full))
    else if (entry.name.endsWith('.arc56.json')) found.push(full)
  }
  return found
}

/** LocalNet-only programs: mocks, probes and stubs that no script deploys to a public network. */
const isTestOnly = (key, name) => /(^|\/)(mocks|tests)\//.test(key) || /^(Mock|Test)[A-Z]/.test(name) || /(Mock|Probe|Stub)/.test(name)

export function buildManifest() {
  const programs = {}
  const compilers = new Set()
  for (const file of specFiles(artifacts)) {
    const spec = JSON.parse(fs.readFileSync(file, 'utf8'))
    const key = path.relative(artifacts, file).split(path.sep).join('/').replace(/\.arc56\.json$/, '')
    if (!spec.byteCode?.approval || !spec.byteCode?.clear) throw new Error(`${key}: the ARC-56 spec has no byteCode`)
    const approval = Buffer.from(spec.byteCode.approval, 'base64')
    const clear = Buffer.from(spec.byteCode.clear, 'base64')
    const v = spec.compilerInfo?.compilerVersion
    compilers.add(`${spec.compilerInfo?.compiler} ${v?.major}.${v?.minor}.${v?.patch}`)
    const templateVariables = Object.keys(spec.templateVariables ?? {}).sort()
    programs[key] = {
      name: spec.name,
      ...(isTestOnly(key, spec.name) ? { testOnly: true } : {}),
      approval: { bytes: approval.length, sha256: sha256(approval) },
      clear: { bytes: clear.length, sha256: sha256(clear) },
      extraPages: Math.max(0, Math.ceil((approval.length + clear.length) / 2048) - 1),
      ...(templateVariables.length ? { templateVariables } : {}),
    }
  }
  if (compilers.size !== 1) throw new Error(`the artifacts were built by more than one compiler: ${[...compilers].join(', ')}`)
  const pkg = JSON.parse(fs.readFileSync(path.join(project, 'package.json'), 'utf8'))
  const sorted = Object.fromEntries(Object.keys(programs).sort().map((key) => [key, programs[key]]))
  return {
    about: 'Generated by scripts/release-manifest.mjs from smart_contracts/artifacts. Do not edit by hand.',
    compiler: {
      puya: [...compilers][0].replace(/^puya /, ''),
      puyaTs: pkg.devDependencies?.['@algorandfoundation/puya-ts'] ?? pkg.dependencies?.['@algorandfoundation/puya-ts'] ?? null,
    },
    programs: sorted,
  }
}

export const serialize = (manifest) => `${JSON.stringify(manifest, null, 2)}\n`

/** Differences between the committed manifest and the artifacts, one line each. Empty when they agree. */
export function diffManifest(committed, built) {
  const lines = []
  if (JSON.stringify(committed.compiler) !== JSON.stringify(built.compiler)) {
    lines.push(`compiler: manifest ${JSON.stringify(committed.compiler)}, artifacts ${JSON.stringify(built.compiler)}`)
  }
  const keys = [...new Set([...Object.keys(committed.programs ?? {}), ...Object.keys(built.programs)])].sort()
  for (const key of keys) {
    const was = committed.programs?.[key]
    const now = built.programs[key]
    if (!was) lines.push(`${key}: built but not in the manifest`)
    else if (!now) lines.push(`${key}: in the manifest but not built`)
    else if (JSON.stringify(was) !== JSON.stringify(now)) {
      const part = was.approval.sha256 !== now.approval.sha256 ? 'approval' : was.clear.sha256 !== now.clear.sha256 ? 'clear' : 'details'
      lines.push(`${key}: ${part} changed (approval ${was.approval.bytes} B ${was.approval.sha256.slice(0, 12)} -> ${now.approval.bytes} B ${now.approval.sha256.slice(0, 12)})`)
    }
  }
  return lines
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const built = buildManifest()
  const count = Object.keys(built.programs).length
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(manifestPath)) {
      console.error(`release/manifest.json does not exist. Run: npm run release:manifest`)
      process.exit(1)
    }
    const lines = diffManifest(JSON.parse(fs.readFileSync(manifestPath, 'utf8')), built)
    if (lines.length) {
      console.error(`The artifacts differ from release/manifest.json in ${lines.length} place(s):`)
      for (const line of lines) console.error(`  ${line}`)
      console.error('If the change is intended, run `npm run release:manifest` and commit the manifest with the artifacts.')
      process.exit(1)
    }
    console.log(`release/manifest.json matches the artifacts: ${count} programs, puya ${built.compiler.puya}, puya-ts ${built.compiler.puyaTs}`)
  } else {
    fs.mkdirSync(path.dirname(manifestPath), { recursive: true })
    fs.writeFileSync(manifestPath, serialize(built))
    console.log(`Wrote release/manifest.json: ${count} programs, puya ${built.compiler.puya}, puya-ts ${built.compiler.puyaTs}`)
  }
}
